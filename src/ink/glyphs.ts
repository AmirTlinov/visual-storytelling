// Indices retain the numeral's pen order, proportions and recognizable form.
for (const [digits, scale, top] of [
  ['⁰¹²³⁴⁵⁶⁷⁸⁹', 0.6, -0.4],
  ['₀₁₂₃₄₅₆₇₈₉', 0.6, 7.4],
] as const) {
  [...digits].forEach((character, i) => {
    let coordinate = 0;
    glyphs[character] = glyphs[String(i)]!.map((path) =>
      path.replace(/-?(?:\d*\.)?\d+/g, (value) => {
        const next = Number(value) * scale + (coordinate++ % 2 ? top : 0.7);
        return String(Math.round(next * 1000) / 1000);
      }),
    );
  });
}

