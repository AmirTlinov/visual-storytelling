import R from '@dimforge/rapier2d-compat';
import { writeFile } from 'node:fs/promises';
import { format } from 'prettier';

// Dimensionless fixed-pivot rotor: inertia = 1, torque = cos(angle), initially at rest.
// Physical trials use s = t sqrt(|tau(0)| / I). No per-question answers are recorded.
await R.init();
const world = new R.World({ x: 0, y: 0 });
const dt = 1 / 3840,
  stride = 32,
  limit = Math.PI / 10;
world.timestep = dt;
const body = world.createRigidBody(
  R.RigidBodyDesc.dynamic()
    .lockTranslations()
    .setCanSleep(false)
    .setLinearDamping(0)
    .setAngularDamping(0)
    .setAdditionalMassProperties(1, { x: 0, y: 0 }, 1),
);
const rows = [[0, 0]];
let step = 0;
try {
  while (body.rotation() < limit) {
    body.resetTorques(false);
    body.addTorque(Math.cos(body.rotation()), true);
    world.step();
    if (++step % stride === 0) rows.push([body.rotation(), body.angvel()]);
  }
  // The final ordinary sample brackets contact; runtime interpolates to the exact stop.
  if (step % stride) rows.push([body.rotation(), body.angvel()]);
  const times = rows.map((_, i) => (i === rows.length - 1 ? step * dt : i * dt * stride));
  const output =
    `// Generated by tools/physics/lever-trajectory.mjs with Rapier 2D 0.21.0.\n` +
    `// theta'' = cos(theta); no damping; integration dt=1/3840, samples at 1/120.\n` +
    `export const leverStopAngle = Math.PI / 10;\n` +
    `export const leverTrajectory: readonly (readonly [number, number, number])[] = ${JSON.stringify(rows.map(([a, v], i) => [times[i], Number(a.toFixed(9)), Number(v.toFixed(9))]))};\n`;
  await writeFile(
    new URL('../../src/math/lever-trajectory.ts', import.meta.url),
    await format(output, { parser: 'typescript' }),
  );
} finally {
  world.free();
}
